package app.jarvis.ui;

import app.jarvis.core.voice.ProviderInfo;
import app.jarvis.core.voice.ProviderStatus;
import app.jarvis.core.voice.SttProvider;
import app.jarvis.core.voice.TtsProvider;

/**
 * Provider-specific help. Never put benchmark numbers here: actual latency is read
 * from each provider's last test and differs by phone, voice, region, model and network.
 */
public final class ProviderGuides {
    private ProviderGuides() { }

    public static String[] tts(TtsProvider provider) {
        ProviderInfo p = provider.info();
        String first;
        String practice;
        switch (p.id) {
            case "edge":
                first = "Edge Read Aloud: голоса Microsoft, в том числе русские. Хорошо подходит для обычных быстрых ответов без личного API-ключа.";
                practice = "Неофициальный интерфейс. Транспорт WebSocket иногда отказывает при блокировках или неверном времени устройства. Сохраняйте запасной голос.";
                break;
            case "gtts":
                first = "Google Translate: один фиксированный голос для языка. Подходит для коротких фраз, когда не нужно выбирать характер голоса.";
                practice = "Это не официальный TTS API. Длинные тексты разбиваются на фрагменты примерно по 180 символов. Возможны лимиты и остановки.";
                break;
            case "android-tts":
                first = "Системный движок Android использует голоса, которые установлены в настройках телефона. Никакого отдельного API-ключа Jarvis не требуется.";
                practice = "Для реального офлайна скачайте русский голос в Android или установите RHVoice. Некоторые встроенные голоса требуют интернет даже при использовании системного движка.";
                break;
            case "gemini-tts":
                first = "Gemini Flash TTS: выразительная генерация речи с выбором голосов. Полезно для естественной интонации и эмоционального чтения.";
                practice = "Сначала сервис синтезирует аудиофайл, поэтому первые звуки могут приходить позже, чем у потоковой озвучки. Нужен ключ Gemini API и доступная квота.";
                break;
            case "gemini-lite-tts":
                first = "Gemini Flash-Lite TTS: более экономный вариант синтеза для простых коротких ответов. Может быть удобен при частых репликах.";
                practice = "Качество и время начала речи зависят от языка и генерации. Для сложной интонации сравните его с обычным Flash на одинаковой фразе.";
                break;
            case "elevenlabs":
                first = "ElevenLabs: голоса с высокой естественностью, настройкой тембра и возможностью клонирования. Полезно, когда важен узнаваемый голос Jarvis.";
                practice = "Бесплатный тариф имеет ограничения на символы и функции. Выбранный голос и модель заметно влияют на задержку. Без ключа не работает.";
                break;
            case "openrouter-tts":
                first = "OpenRouter TTS: шлюз к моделям, способным озвучивать текст. Возможности зависят от выбранной модели и её формата аудио.";
                practice = "Это не бесплатный локальный TTS. Ошибка 402 означает нехватку средств именно у этого провайдера и не доказывает проблему с DeepSeek.";
                break;
            case "silero":
                first = "Silero Space: русскоязычные голоса, рассчитанные на обычную речь. Подходят для экспериментов с произношением и характером.";
                practice = "Публичное демо может стоять в очереди, засыпать или быть недоступно. Не ставьте его единственным голосом для срочных команд.";
                break;
            case "f5space":
                first = "F5 Space: экспериментальная генерация и клонирование голоса по образцу в публичном пространстве.";
                practice = "Генерация может длиться существенно дольше обычных TTS. Предпочтительна для студийных тестов, а не мгновенных подтверждений.";
                break;
            default:
                first = p.voices + ". " + p.limitations;
                practice = "Проверяйте именно этот провайдер отдельной тестовой фразой, прежде чем включать в цепочку озвучки.";
        }
        return new String[]{
            first,
            "Как подключить: " + (p.needsKey ? "задайте ключ API у этой карточки, затем выберите голос" :
                "при необходимости выберите голос — отдельный ключ не нужен") + ".",
            "Как понять скорость: нажмите «Проверить». Jarvis измерит задержку до первого звука и общее время. " +
                "Результат относится к текущему устройству и сети, а не к рекламным бенчмаркам.",
            practice,
            "Стратегия: включите основной и хотя бы один резервный TTS. Если основной сервис не ответит, Jarvis попробует следующий."
        };
    }

    public static String[] stt(SttProvider provider) {
        ProviderInfo p = provider.info();
        String first, caution;
        switch (p.id) {
            case "vosk-local":
                first = "Vosk слушает локально на устройстве. Для слова «Джарвис» и коротких команд работает без передачи голоса в интернет, если русский пакет установлен.";
                caution = "Компактная офлайн-модель обычно хуже понимает шумную и длинную речь, чем крупные облачные модели.";
                break;
            case "groq-stt":
                first = "Groq Whisper: быстрая облачная транскрипция коротких фраз, русский поддерживается. Бесплатный тариф ограничивает частоту запросов и объём аудио.";
                caution = "Если достигнут дневной лимит или ключ не задан, включите Cloudflare, Gemini или офлайн-резерв.";
                break;
            case "cloudflare-stt":
                first = "Cloudflare Whisper Large v3 Turbo: русский и другие языки через Workers AI. Бесплатная суточная квота делится между всеми моделями аккаунта.";
                caution = "Для работы нужны отдельные Account ID и API Token. Один длинный файл дороже по дневному лимиту, чем короткая команда.";
                break;
            case "gemini-transcribe-stt":
                first = "Gemini 3.5 Transcribe: специализированная расшифровка с форматированием и подсказками для названий вроде «Джарвис» или DeepSeek.";
                caution = "Запись сначала загружается через Files API, поэтому задержка отличается от потокового диктовочного режима.";
                break;
            case "gemini-audio-stt":
                first = "Gemini Audio: мультимодальная модель, которая может понять сказанное по звуку и вернуть текст. Удобна как резерв для неочевидных фраз.";
                caution = "Это не специализированный потоковый диктофон: модель может исправлять смысл вместо дословной расшифровки, поэтому проверяйте точность.";
                break;
            case "elevenlabs-stt":
                first = "ElevenLabs Scribe: отдельная технология распознавания речи, не связанная с тем, каким голосом озвучиваются ответы.";
                caution = "Нужен ElevenLabs API-ключ; проверьте актуальные ограничения на минуты для своего тарифного плана.";
                break;
            case "openrouter-stt":
                first = "OpenRouter Speech-to-Text использует Whisper через платёжный API-шлюз. Он не обязан совпадать с выбранным LLM-провайдером.";
                caution = "HTTP 402 означает недостаток денег на OpenRouter STT. Выключите эту карточку, если хотите бесплатную цепочку.";
                break;
            case "google-stt":
                first = "Старый Google Speech в Jarvis обращается к неофициальному интерфейсу. Может работать на отдельных конфигурациях.";
                caution = "HTTP 403 обычно означает отказ или ограничение на стороне Google. Для стабильного решения лучше выбрать официальный API.";
                break;
            default:
                first = p.voices;
                caution = p.limitations;
        }
        return new String[]{
            first,
            "Шаг 1: " + (p.needsKey ? "сохраните API-ключ конкретного сервиса" : "установите локальную модель, если требуется") + ".",
            "Шаг 2: нажмите «Образец». Jarvis отправит заранее записанную контрольную русскую фразу — так можно проверить провайдера без микрофона.",
            "Шаг 3: нажмите «Проверить микрофон». Только этот тест покажет, работает ли путь записи на вашем телефоне.",
            caution
        };
    }
}
